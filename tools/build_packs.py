import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from packs_code_marketing import CODE, MARKETING
from packs_crypto_writing import CRYPTO, WRITING
out = os.path.join(os.path.dirname(__file__), '..', 'prompt-manager', 'packs')
os.makedirs(out, exist_ok=True)
for pack in (CODE, MARKETING, CRYPTO, WRITING):
    tpls = []
    for tid, tags, en, tr in pack['templates']:
        tpls.append({'id': tid, 'tags': tags, 'en': {'title': en[0], 'body': en[1]}, 'tr': {'title': tr[0], 'body': tr[1]}})
    data = {k: pack[k] for k in ('id', 'version', 'name', 'description')}
    data['templates'] = tpls
    js = ("/* Prompt pack \"%s\" — original templates written for this extension (not copied from other tools). Generated by tools/build_packs.py. */\n"
          "(function (root) {\n  const pack = %s;\n"
          "  if (typeof module === 'object' && module.exports) module.exports = pack;\n"
          "  else { root.PM = root.PM || {}; (root.PM.PACK_DATA = root.PM.PACK_DATA || []).push(pack); }\n"
          "})(typeof self !== 'undefined' ? self : this);\n") % (pack['id'], json.dumps(data, ensure_ascii=False, indent=2).replace('\n', '\n  '))
    open(os.path.join(out, pack['id'] + '.js'), 'w', encoding='utf-8').write(js)
    print(pack['id'], len(tpls))
